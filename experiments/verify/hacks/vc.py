import os, sys, re, tempfile, subprocess as sp, csv
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "common"))
import config
import vm_common  # sets ABC2MIDI_BIN
from mscorer import compute_score, do, analyze
from mscorer.core import parse_midi
from mscorer.feats import _sonorities
ABC2MIDI = os.environ["ABC2MIDI_BIN"]
ROOT = config.EXPERIMENTS  # abc_route/ lives here; abc_norm/ is generated by abc_route/score_abc_route.py
NORM = os.path.join(ROOT, "abc_route", "abc_norm")

def S(abc):
    return compute_score("music", "```abc\n" + abc + "\n```")

def midi(abc):
    with tempfile.TemporaryDirectory() as td:
        ap, mp = td + "/a.abc", td + "/a.mid"
        open(ap, "w").write(abc)
        p = sp.run([ABC2MIDI, ap, "-o", mp], capture_output=True, timeout=60)
        log = (p.stdout + p.stderr).decode("utf-8", "replace")
        m = parse_midi(open(mp, "rb").read()) if os.path.exists(mp) else None
        f = analyze(mp) if os.path.exists(mp) else None
    return m, log, f

def rec(abc):
    return do(dict(key="k", id=0, rep=0, abc=abc))

def pieces(passing_only=True):
    rows = list(csv.DictReader(open(os.path.join(ROOT, "abc_route", "per_piece.csv"))))
    out = []
    for r in rows:
        if passing_only and not (r["gates_norm"] == "" and r["quality_norm_ungated"]):
            continue
        out.append((r["id"], r["title"], open(os.path.join(NORM, r["id"] + ".abc")).read(), r))
    return out
